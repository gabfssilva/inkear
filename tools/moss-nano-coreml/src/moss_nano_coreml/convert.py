"""Export MOSS-TTS-Nano to Core ML packages for the Neural Engine, with what the Swift side needs."""

import argparse
import base64
import json
import shutil
import tempfile
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

import coremltools as ct
import numpy as np
import torch
from sentencepiece import sentencepiece_model_pb2
from torch import nn

from moss_nano_coreml import graphs, pipeline, reference, voices

BUILD = Path(__file__).resolve().parents[2] / "build" / "moss-nano"
PREFILL_ROWS = (128, 256, 512)
CONTEXTS = (256, 512, 1024)
# RVQ depths generated by the local decoder; 8 was measured unintelligible (WER ~1.0 pt, ~0.5 en).
CODEBOOK_DEPTHS = (16, 12)
CHUNK_FRAMES = 12
F16 = np.float16


@dataclass(frozen=True)
class Function:
    name: str
    build: Callable[[], nn.Module]
    inputs: Sequence[ct.TensorType]
    outputs: Sequence[str]


def _example(spec: ct.TensorType) -> torch.Tensor:
    shape = tuple(int(dim) for dim in spec.shape.shape)
    return torch.zeros(shape, dtype=torch.int32 if spec.dtype == np.int32 else torch.float32)


def convert(function: Function) -> ct.models.MLModel:
    module = function.build().eval()
    traced = torch.jit.trace(module, tuple(_example(spec) for spec in function.inputs))
    return ct.convert(
        traced,
        inputs=list(function.inputs),
        outputs=[ct.TensorType(name, dtype=F16) for name in function.outputs],
        convert_to="mlprogram",
        compute_precision=ct.precision.FLOAT16,
        minimum_deployment_target=ct.target.iOS18,
    )


def package(name: str, functions: Sequence[Function], directory: Path) -> Path:
    """One multifunction package; identical weights are stored once. The first function is the default."""
    descriptor = ct.utils.MultiFunctionDescriptor()
    with tempfile.TemporaryDirectory() as scratch:
        for function in functions:
            print(f"  {name}.{function.name}", flush=True)
            single = Path(scratch) / f"{function.name}.mlpackage"
            convert(function).save(str(single))
            descriptor.add_function(str(single), src_function_name="main", target_function_name=function.name)
        descriptor.default_function_name = functions[0].name
        path = directory / f"{name}.mlpackage"
        shutil.rmtree(path, ignore_errors=True)
        ct.utils.save_multifunction(descriptor, str(path))
    return path


def tensor(name: str, shape: tuple[int, ...], dtype: type[np.generic] = F16) -> ct.TensorType:
    return ct.TensorType(name=name, shape=shape, dtype=dtype)


def global_functions(model: nn.Module) -> list[Function]:
    cache = (graphs.LAYERS, graphs.HEADS)
    prefill = [
        Function(
            name=f"prefill_{rows}",
            build=lambda rows=rows: graphs.GlobalPrefill(model, rows),
            inputs=[tensor("rows", (rows, 17), np.int32)],
            outputs=["hidden", "keys", "values"],
        )
        for rows in PREFILL_ROWS
    ]
    step = [
        Function(
            name=f"step_{context}",
            build=lambda: graphs.GlobalStep(model),
            inputs=[
                tensor("row", (1, 17), np.int32),
                tensor("key_cache", (*cache, context, graphs.HEAD_DIM)),
                tensor("value_cache", (*cache, context, graphs.HEAD_DIM)),
                tensor("mask", (1, context)),
                tensor("cos", (1, graphs.HEAD_DIM)),
                tensor("sin", (1, graphs.HEAD_DIM)),
            ],
            outputs=["hidden", "key", "value"],
        )
        for context in CONTEXTS
    ]
    return [*step, *prefill]


def local_functions(model: nn.Module) -> list[Function]:
    return [
        Function(
            name=f"frame_{depth}",
            build=lambda depth=depth: graphs.LocalSampler(model, depth),
            inputs=[
                tensor("hidden", (1, graphs.HIDDEN)),
                tensor("seen", (depth, graphs.CODEBOOK_SIZE)),
                tensor("gumbel", (depth, graphs.CANDIDATES)),
                tensor("text_gumbel", (1, 2)),
                tensor("settings", (1, 6)),
            ],
            outputs=["end", "codes"],
        )
        for depth in CODEBOOK_DEPTHS
    ]


def codec_caches(codec: nn.Module) -> list[tuple[str, tuple[int, ...]]]:
    stages = graphs.CodecDecoder(codec, CHUNK_FRAMES).stages
    return [
        (f"{kind}_{index}", (len(stage.layers), graphs.CODEC_HEADS, stage.cache, graphs.CODEC_HEAD_DIM))
        for index, stage in enumerate(stages)
        for kind in ("keys", "values")
    ]


def codec_functions(codec: nn.Module) -> list[Function]:
    caches = codec_caches(codec)
    return [
        Function(
            name=f"chunk_{CHUNK_FRAMES}",
            build=lambda: graphs.CodecDecoder(codec, CHUNK_FRAMES),
            inputs=[
                tensor("codes", (CHUNK_FRAMES, graphs.CODEBOOKS)),
                tensor("past_frames", (1, 1)),
                *(tensor(name, shape) for name, shape in caches),
            ],
            outputs=["audio", *(f"new_{name}" for name, _ in caches)],
        )
    ]


def tokenizer_json(model_file: Path) -> Mapping[str, object]:
    """The SentencePiece model in speech-swift's `moss_sentencepiece_bpe_v1` layout (MossTTSNanoTokenizer)."""
    proto = sentencepiece_model_pb2.ModelProto()
    proto.ParseFromString(model_file.read_bytes())
    return {
        "format": "moss_sentencepiece_bpe_v1",
        "pieces": [{"text": piece.piece, "score": piece.score, "type": piece.type} for piece in proto.pieces],
        "precompiled_charsmap": base64.b64encode(proto.normalizer_spec.precompiled_charsmap).decode(),
    }


def config(codec: nn.Module) -> Mapping[str, object]:
    sampling = reference.Sampling()
    return {
        "model_type": "moss_tts_nano_ane",
        "source": {
            "model": f"{reference.MODEL_REPO}@{reference.MODEL_REVISION}",
            "codec": f"{reference.CODEC_REPO}@{reference.CODEC_REVISION}",
            "license": "Apache-2.0",
        },
        "sample_rate": reference.SAMPLE_RATE,
        "channels": 2,
        "samples_per_frame": reference.SAMPLES_PER_FRAME,
        "frames_per_second": graphs.FRAMES_PER_SECOND,
        "codebooks": graphs.CODEBOOKS,
        "codebook_size": graphs.CODEBOOK_SIZE,
        "audio_pad_id": graphs.AUDIO_PAD,
        "hidden_size": graphs.HIDDEN,
        "layers": graphs.LAYERS,
        "heads": graphs.HEADS,
        "head_dim": graphs.HEAD_DIM,
        "rope_base": 10000.0,
        "masked": graphs.MASKED,
        "candidates": graphs.CANDIDATES,
        "prefill_rows": list(PREFILL_ROWS),
        "contexts": list(CONTEXTS),
        "codebook_depths": list(CODEBOOK_DEPTHS),
        "chunk_frames": CHUNK_FRAMES,
        "codec_window_frames": 125,
        "codec_caches": {name: list(shape) for name, shape in codec_caches(codec)},
        "tokens": {
            "pad": 3,
            "im_start": 4,
            "im_end": 5,
            "audio_start": 6,
            "audio_end": 7,
            "audio_user_slot": 8,
            "audio_assistant_slot": 9,
        },
        "prompt": {
            "user_prefix": "user\n",
            "reference_prefix": "<user_inst>\n- Reference(s):\n",
            "after_reference": "\n- Instruction:\nNone\n- Tokens:\nNone\n- Quality:\nNone\n- Sound Event:\nNone\n"
            "- Ambient Sound:\nNone\n- Language:\nNone\n- Text:\n",
            "user_suffix": "\n</user_inst>",
            "assistant_prefix": "\n",
            "assistant_role": "assistant\n",
        },
        "sampling": {
            "text_temperature": sampling.text_temperature,
            "audio_temperature": sampling.audio_temperature,
            "audio_top_k": sampling.audio_top_k,
            "audio_top_p": sampling.audio_top_p,
            "audio_repetition_penalty": sampling.audio_repetition_penalty,
        },
        "quality": {
            name: {"codebooks": level.depth, "retries": level.retries}
            for name, level in pipeline.QUALITY.items()
        },
        "plausible_frames_per_token": list(pipeline.PLAUSIBLE_FRAMES_PER_TOKEN),
        "max_frames": pipeline.MAX_FRAMES,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=f"Export MOSS-TTS-Nano for the Neural Engine into {BUILD}")
    parser.add_argument(
        "--only", choices=("GlobalDecoder", "LocalDecoder", "CodecDecoder", "assets"), action="append"
    )
    args = parser.parse_args()
    selected = set(args.only or ("GlobalDecoder", "LocalDecoder", "CodecDecoder", "assets"))
    BUILD.mkdir(parents=True, exist_ok=True)
    source = reference.load()
    if "assets" in selected:
        print("assets", flush=True)
        shutil.copy(source.root / "tokenizer.model", BUILD / "tokenizer.model")
        (BUILD / "tokenizer.json").write_text(
            json.dumps(tokenizer_json(source.root / "tokenizer.model")) + "\n"
        )
        (BUILD / "config.json").write_text(
            json.dumps(config(source.codec), indent=2, ensure_ascii=False) + "\n"
        )
        for voice in voices.VOICES:
            print(f"  voice {voice.name}", flush=True)
            voices.prepare(voice, BUILD.parent / "downloads", BUILD / "voices")
    builders: Mapping[str, Callable[[], list[Function]]] = {
        "GlobalDecoder": lambda: global_functions(source.model),
        "LocalDecoder": lambda: local_functions(source.model),
        "CodecDecoder": lambda: codec_functions(source.codec),
    }
    for name, build in builders.items():
        if name in selected:
            print(name, flush=True)
            print(f"  -> {package(name, build(), BUILD)}", flush=True)
